#!/usr/bin/env python3
"""Resolve a plain-text "Artist - Title" tracklist against the Apple Music catalogue.

Each line is "Artist - Title", optionally followed by " | Album" to steer the
match towards a particular release.

Uses Apple's public iTunes Search API (no key, no account). For every line it
fetches a page of candidates, scores each one on artist and title similarity,
and keeps the best match above a confidence threshold. Results are cached so a
re-run only looks up what is still missing.

Outputs (in --out, default ./out):
  matched.json        full detail for every line, including score and Apple IDs
  links.txt           one Apple Music URL per confident match, in playlist order
  ids.txt             the matching Apple Music song IDs, in playlist order
  report.md           human-readable table: confident, review, and missed tracks
  build_playlist.js   paste into the browser console on music.apple.com to
                      create the playlist in your library (see README)

Standard library only. Python 3.9+.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from difflib import SequenceMatcher
from pathlib import Path

API = "https://itunes.apple.com/search"
# Apple documents the Search API at roughly 20 calls a minute.
MIN_INTERVAL = 3.2
NOISE = ("karaoke", "tribute", "originally performed", "in the style of",
         "made famous", "cover version", "8-bit", "lullaby", "ringtone")

JS_TEMPLATE = r"""// Generated by resolve.py. Creates an Apple Music playlist from resolved song IDs.
// How to use: open https://music.apple.com in a desktop browser, sign in,
// open the developer console, paste this whole file, press Return.
(async () => {
  const NAME = __NAME__;
  const DESCRIPTION = __DESCRIPTION__;
  const IDS = __IDS__;
  const BATCH = 25;

  if (typeof MusicKit === "undefined") throw new Error("Run this on music.apple.com");
  const mk = MusicKit.getInstance();
  if (!mk.isAuthorized) await mk.authorize();

  // MusicKit builds differ on where they read fetch options, so pass both shapes.
  const post = async (path, body) => {
    const init = { method: "POST", body: JSON.stringify(body) };
    const res = await mk.api.music(path, {}, { ...init, fetchOptions: init });
    const status = res && (res.status || (res.response && res.response.status));
    const errors = res && res.data && res.data.errors;
    if (errors || (status && status >= 400)) {
      throw new Error(`Apple Music said no (${status}): ${JSON.stringify(errors || "")}`);
    }
    return res;
  };
  const asTracks = (ids) => ids.map((id) => ({ id: String(id), type: "songs" }));

  // Create the playlist with the first batch.
  const created = await post("/v1/me/library/playlists", {
    attributes: { name: NAME, description: DESCRIPTION },
    relationships: { tracks: { data: asTracks(IDS.slice(0, BATCH)) } },
  });
  const playlist = created && created.data && created.data.data && created.data.data[0];
  // Safety check: only carry on if Apple handed back the playlist we just made.
  if (!playlist || !playlist.attributes || playlist.attributes.name !== NAME) {
    throw new Error("Playlist was not created; stopping before touching anything else.");
  }

  // Append the rest in order.
  for (let i = BATCH; i < IDS.length; i += BATCH) {
    await post(`/v1/me/library/playlists/${playlist.id}/tracks`, {
      data: asTracks(IDS.slice(i, i + BATCH)),
    });
    await new Promise((r) => setTimeout(r, 500));
  }
  console.log(`Created "${NAME}" with ${IDS.length} tracks (${playlist.id}).`);
  return { playlistId: playlist.id, name: playlist.attributes.name, tracks: IDS.length };
})();
"""

_last_call = 0.0


def norm(text: str) -> str:
    """Lower-case, strip accents and punctuation, collapse whitespace."""
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c)).lower()
    text = text.replace("&", " and ")
    text = re.sub(r"[^a-z0-9 ]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def strip_parens(text: str) -> str:
    return re.sub(r"\s*[\(\[][^\)\]]*[\)\]]", "", text).strip()


def sim(a: str, b: str) -> float:
    a, b = norm(a), norm(b)
    if not a or not b:
        return 0.0
    if a == b:
        return 1.0
    ratio = SequenceMatcher(None, a, b).ratio()
    # Reward whole-word containment ("Portishead" in "Portishead and Friends").
    if f" {a} " in f" {b} " or f" {b} " in f" {a} ":
        ratio = max(ratio, 0.85)
    return ratio


UNWANTED = ("live", "remix", "version", "instrumental", "acoustic", "edit",
            "demo", "mix", "rework", "versions", "remixes", "remixed")


def album_matches(hint: str, cand: dict) -> bool:
    if not hint:
        return False
    return sim(hint, cand.get("collectionName", "")) >= 0.8


def score(artist: str, title: str, cand: dict, album: str = "") -> tuple[float, float]:
    """Return (identity, rank).

    identity says how sure we are this is the right song (artist and title).
    rank breaks ties between several releases of that song: it prefers the
    album you named, streamable releases, and the plain studio recording over
    live cuts, remixes and compilations.
    """
    c_artist = cand.get("artistName", "")
    c_title = cand.get("trackName", "")
    split = r"\s*(?:&|,| feat\.? | and | x )\s*"
    wanted_parts = [p for p in re.split(split, artist) if p]
    cand_parts = [p for p in re.split(split, c_artist) if p]
    a = max([sim(artist, c_artist)]
            + [sim(p, c_artist) * 0.95 for p in wanted_parts]
            + [sim(artist, p) * 0.97 for p in cand_parts])
    t = max(sim(title, c_title),
            sim(strip_parens(title), strip_parens(c_title)) * 0.93)
    identity = 0.45 * a + 0.55 * t
    blob = norm(f"{c_artist} {c_title} {cand.get('collectionName', '')}")
    if any(n in blob for n in NOISE):
        identity -= 0.25
    identity = round(max(identity, 0.0), 3)

    rank = identity
    if album_matches(album, cand):
        rank += 0.05
    if cand.get("isStreamable") is False:
        rank -= 0.08
    if "various" in norm(cand.get("collectionArtistName", "")):
        rank -= 0.03
    asked = set(norm(f"{title} {album}").split())
    found = set(norm(f"{c_title} {cand.get('collectionName', '')}").split())
    rank -= 0.05 * sum(1 for tag in UNWANTED if tag in found and tag not in asked)
    # A bracketed qualifier the list did not ask for ("(Someone's ReRub)") is
    # usually a different recording. Guest credits are fine.
    for extra in re.findall(r"[\(\[]([^\)\]]*)[\)\]]", c_title):
        if not norm(extra).startswith(("feat", "with ")) and norm(extra) not in norm(title):
            rank -= 0.05
    return identity, round(rank, 3)


def search(term: str, country: str, limit: int = 25) -> list[dict]:
    """One rate-limited call to the iTunes Search API, with back-off."""
    global _last_call
    query = urllib.parse.urlencode({
        "term": term, "country": country, "media": "music",
        "entity": "song", "limit": limit,
    })
    for attempt in range(5):
        wait = MIN_INTERVAL - (time.monotonic() - _last_call)
        if wait > 0:
            time.sleep(wait)
        _last_call = time.monotonic()
        try:
            req = urllib.request.Request(f"{API}?{query}",
                                         headers={"User-Agent": "tracklist-resolver/1.0"})
            with urllib.request.urlopen(req, timeout=20) as resp:
                return json.loads(resp.read().decode("utf-8")).get("results", [])
        except urllib.error.HTTPError as err:
            if err.code in (403, 429, 502, 503):
                time.sleep(20 * (attempt + 1))
                continue
            raise
        except (urllib.error.URLError, TimeoutError):
            time.sleep(5 * (attempt + 1))
    return []


def resolve(artist: str, title: str, country: str, album: str = "") -> dict:
    """Try progressively looser queries; return the best-ranked candidate."""
    queries = [f"{artist} {title}"]
    if album:
        queries.append(f"{artist} {title} {album}")
    if strip_parens(title) != title:
        queries.append(f"{artist} {strip_parens(title)}")
    queries.append(title)
    best, best_id, best_rank, tried = None, 0.0, -1.0, []
    for q in dict.fromkeys(queries):
        tried.append(q)
        for cand in search(q, country, limit=50):
            if cand.get("kind") != "song":
                continue
            identity, rank = score(artist, title, cand, album)
            if rank > best_rank:
                best, best_id, best_rank = cand, identity, rank
        if best_id >= 0.9 and (not album or album_matches(album, best)):
            break
        if best_id >= 0.9 and len(tried) >= 2:
            break
    out = {"artist": artist, "title": title, "album": album, "score": best_id, "queries": tried}
    if best:
        out.update({
            "trackId": best["trackId"],
            "matchArtist": best.get("artistName"),
            "matchTitle": best.get("trackName"),
            "matchAlbum": best.get("collectionName"),
            "year": (best.get("releaseDate") or "")[:4],
            "url": (best.get("trackViewUrl") or "").split("&uo=")[0].split("?uo=")[0],
            "streamable": best.get("isStreamable"),
        })
    return out


def parse_tracklist(text: str) -> list[tuple[str, str, str]]:
    """Parse lines of "Artist - Title" with an optional " | Album" hint."""
    tracks = []
    for line in text.splitlines():
        line = re.sub(r"^\s*(?:\d+[.)]|[•*])\s+", "", line).strip()
        if not line or line.startswith("#"):
            continue
        album = ""
        if " | " in line:
            line, album = (part.strip() for part in line.rsplit(" | ", 1))
        for sep in (" - ", " – ", " — "):
            if sep in line:
                artist, title = line.split(sep, 1)
                tracks.append((artist.strip(), title.strip().strip('"“”'), album))
                break
    return tracks


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("tracklist", help='text file of "Artist - Title" lines (optional " | Album"), or - for stdin')
    ap.add_argument("--country", default="AU", help="storefront code, e.g. AU, US, GB (default AU)")
    ap.add_argument("--out", default="out", help="output folder (default ./out)")
    ap.add_argument("--name", help="playlist name (default: tracklist file name)")
    ap.add_argument("--description", default="", help="playlist description")
    ap.add_argument("--include-review", action="store_true",
                    help="also add 'review' matches to links.txt, ids.txt and build_playlist.js")
    ap.add_argument("--confident", type=float, default=0.86, help="score at or above this is a confident match")
    ap.add_argument("--review", type=float, default=0.70, help="score at or above this is listed for review")
    args = ap.parse_args()

    text = sys.stdin.read() if args.tracklist == "-" else Path(args.tracklist).read_text(encoding="utf-8")
    tracks = parse_tracklist(text)
    if not tracks:
        print("No 'Artist - Title' lines found.", file=sys.stderr)
        return 1

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    cache_path = out / "matched.json"
    cache = {}
    if cache_path.exists():
        for row in json.loads(cache_path.read_text(encoding="utf-8")):
            if row.get("country") == args.country:
                cache[(row["artist"], row["title"], row.get("album", ""))] = row

    rows = []
    todo = sum(1 for t in tracks if t not in cache)
    if todo:
        print(f"Resolving {todo} of {len(tracks)} tracks against the {args.country} storefront "
              f"(about {todo * MIN_INTERVAL * 1.4 / 60:.0f} min; Apple allows ~20 lookups a minute)...")
    for i, (artist, title, album) in enumerate(tracks, 1):
        row = cache.get((artist, title, album))
        if row is None:
            row = resolve(artist, title, args.country, album)
            row["country"] = args.country
            flag = "ok " if row["score"] >= args.confident else ("?? " if row["score"] >= args.review else "-- ")
            print(f"  {i:>3}/{len(tracks)} {flag}{row['score']:.2f}  {artist} - {title}", flush=True)
        row["n"] = i
        rows.append(row)
        cache_path.write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")

    good = [r for r in rows if r["score"] >= args.confident and r.get("url")]
    review = [r for r in rows if args.review <= r["score"] < args.confident and r.get("url")]
    missed = [r for r in rows if r["score"] < args.review or not r.get("url")]

    chosen = sorted(good + (review if args.include_review else []), key=lambda r: r["n"])
    name = args.name or ("Playlist" if args.tracklist == "-" else
                         Path(args.tracklist).stem.replace("-", " ").replace("_", " ").title())
    (out / "links.txt").write_text("\n".join(r["url"] for r in chosen) + "\n", encoding="utf-8")
    (out / "ids.txt").write_text("\n".join(str(r["trackId"]) for r in chosen) + "\n", encoding="utf-8")
    (out / "build_playlist.js").write_text(
        JS_TEMPLATE.replace("__NAME__", json.dumps(name))
                   .replace("__DESCRIPTION__", json.dumps(args.description))
                   .replace("__IDS__", json.dumps([r["trackId"] for r in chosen])),
        encoding="utf-8")

    def table(items):
        lines = ["| # | Asked for | Matched | Album | Score |", "|---|---|---|---|---|"]
        for r in items:
            matched = f"[{r.get('matchArtist')} - {r.get('matchTitle')}]({r.get('url')})" if r.get("url") else "none"
            lines.append(f"| {r['n']} | {r['artist']} - {r['title']} | {matched} | {r.get('matchAlbum') or ''} | {r['score']:.2f} |")
        return "\n".join(lines)

    report = [f"# Match report ({args.country} storefront)", "",
              f"{len(good)} confident, {len(review)} to review, {len(missed)} missed, {len(rows)} total.", ""]
    if review:
        report += ["## Review these", "", table(review), ""]
    if missed:
        report += ["## Missed", "", table(missed), ""]
    report += ["## Confident matches", "", table(good), ""]
    (out / "report.md").write_text("\n".join(report), encoding="utf-8")

    print(f"\n{len(good)} confident, {len(review)} to review, {len(missed)} missed.")
    print(f"{len(chosen)} tracks written to {out/'build_playlist.js'}, {out/'links.txt'} and {out/'ids.txt'}.")
    print(f"Details in {out/'report.md'} and {out/'matched.json'}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
